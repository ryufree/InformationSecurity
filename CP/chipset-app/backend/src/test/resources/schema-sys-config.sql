-- H2 테스트용 SYS_CONFIG 테이블 (Oracle 시퀀스 대신 AUTO_INCREMENT)
CREATE TABLE IF NOT EXISTS SYS_CONFIG (
    CONFIG_ID   BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PROFILE     VARCHAR(50)  NOT NULL,
    PROP_KEY    VARCHAR(200) NOT NULL,
    PROP_VALUE  VARCHAR(2000),
    DATA_TYPE   VARCHAR(20)  DEFAULT 'STRING',
    EDITABLE_YN CHAR(1)      DEFAULT 'Y',
    RESTART_YN  CHAR(1)      DEFAULT 'N',
    DESCRIPTION VARCHAR(500),
    USE_YN      CHAR(1)      DEFAULT 'Y',
    REG_DT      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    MOD_DT      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SYS_CONFIG     PRIMARY KEY (CONFIG_ID),
    CONSTRAINT UK_SYS_CONFIG_KEY UNIQUE (PROFILE, PROP_KEY)
);
