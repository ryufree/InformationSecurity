-- H2 Oracle-compatibility mode DDL
-- Oracle 배포 시: 이 파일 대신 design.md 8번 섹션 DDL을 DBeaver에서 실행

-- ── 시퀀스 ──────────────────────────────────────────────────────
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_UPLOAD     START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_CHIP_COL   START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_ROW        START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_CELL       START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_UPLOAD_H   START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_CHIP_COL_H START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_ROW_H      START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_CHIPSET_CELL_H     START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_RAWDATA_ROW        START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS SQ_RAWDATA_ROW_H      START WITH 1 INCREMENT BY 1;

-- ── 메인: 업로드 이력 ─────────────────────────────────────────
-- FILE_TYPE: 'SERVER' | 'CLIENT' | 'MOBILE' | 'RAW_DATA'
CREATE TABLE IF NOT EXISTS CHIPSET_UPLOAD (
    UPLOAD_SEQ  NUMBER        NOT NULL,
    FILE_NM     VARCHAR2(255) NOT NULL,
    FILE_TYPE   VARCHAR2(20)  DEFAULT 'SERVER' NOT NULL,
    UPLOAD_DT   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ROW_COUNT   NUMBER        DEFAULT 0,
    COL_COUNT   NUMBER        DEFAULT 0,
    CONSTRAINT PK_CHIPSET_UPLOAD PRIMARY KEY (UPLOAD_SEQ)
);

-- ── 메인: 칩 컬럼 (동적 벤더) ────────────────────────────────
CREATE TABLE IF NOT EXISTS CHIPSET_CHIP_COL (
    COL_SEQ     NUMBER        NOT NULL,
    UPLOAD_SEQ  NUMBER        NOT NULL,
    VENDOR      VARCHAR2(100) NOT NULL,
    COL_IDX     NUMBER        NOT NULL,
    CHIP_NM     VARCHAR2(200) NOT NULL,
    CHIP_DT     VARCHAR2(50),
    SORT_ORDER  NUMBER        DEFAULT 0,
    CONSTRAINT PK_CHIPSET_CHIP_COL PRIMARY KEY (COL_SEQ),
    CONSTRAINT FK_CHIP_COL_UPLOAD FOREIGN KEY (UPLOAD_SEQ)
        REFERENCES CHIPSET_UPLOAD (UPLOAD_SEQ)
);

-- ── 메인: 스펙 행 (Server/Client: DIMM~Speed, Mobile: PKG/P.N 재사용) ──
CREATE TABLE IF NOT EXISTS CHIPSET_ROW (
    ROW_SEQ     NUMBER        NOT NULL,
    UPLOAD_SEQ  NUMBER        NOT NULL,
    DIMM        VARCHAR2(100),
    PRODUCT     VARCHAR2(200),
    VER         VARCHAR2(50),
    DENSITY     VARCHAR2(50),
    ORG         VARCHAR2(50),
    SPEED       VARCHAR2(100),
    SORT_ORDER  NUMBER        DEFAULT 0,
    CONSTRAINT PK_CHIPSET_ROW PRIMARY KEY (ROW_SEQ),
    CONSTRAINT FK_ROW_UPLOAD FOREIGN KEY (UPLOAD_SEQ)
        REFERENCES CHIPSET_UPLOAD (UPLOAD_SEQ)
);

-- ── 메인: 셀 값 ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS CHIPSET_CELL (
    CELL_SEQ    NUMBER        NOT NULL,
    ROW_SEQ     NUMBER        NOT NULL,
    COL_SEQ     NUMBER        NOT NULL,
    CELL_VALUE  VARCHAR2(200),
    BG_COLOR    VARCHAR2(10),
    CONSTRAINT PK_CHIPSET_CELL PRIMARY KEY (CELL_SEQ),
    CONSTRAINT FK_CELL_ROW FOREIGN KEY (ROW_SEQ)
        REFERENCES CHIPSET_ROW (ROW_SEQ),
    CONSTRAINT FK_CELL_COL FOREIGN KEY (COL_SEQ)
        REFERENCES CHIPSET_CHIP_COL (COL_SEQ)
);

-- ── 메인: Raw_Data 행 (Tracking 형식 전용) ───────────────────
CREATE TABLE IF NOT EXISTS RAWDATA_ROW (
    RAWDATA_ROW_SEQ NUMBER        NOT NULL,
    UPLOAD_SEQ      NUMBER        NOT NULL,
    COMPANY         VARCHAR2(100),
    SEG             VARCHAR2(100),
    CHIPSET         VARCHAR2(200),
    SOC_CS          VARCHAR2(200),
    PART_NUMBER     VARCHAR2(200),
    DRAM_PROCESS    VARCHAR2(100),
    FLASH_PROCESS   VARCHAR2(100),
    DENSITY         VARCHAR2(50),
    MLC_TLC         VARCHAR2(50),
    PKG             VARCHAR2(200),
    VAL1_DATE       VARCHAR2(20),
    VAL1_ENG        VARCHAR2(50),
    VAL1_STATUS     VARCHAR2(50),
    VAL1_REMARK     VARCHAR2(500),
    VAL2_DATE       VARCHAR2(20),
    VAL2_ENG        VARCHAR2(50),
    VAL2_STATUS     VARCHAR2(50),
    VAL2_REMARK     VARCHAR2(500),
    VAL3_DATE       VARCHAR2(20),
    VAL3_ENG        VARCHAR2(50),
    SORT_ORDER      NUMBER        DEFAULT 0,
    CONSTRAINT PK_RAWDATA_ROW PRIMARY KEY (RAWDATA_ROW_SEQ)
);

-- ── 히스토리: 업로드 ──────────────────────────────────────────
CREATE TABLE IF NOT EXISTS CHIPSET_UPLOAD_H (
    UPLOAD_H_SEQ NUMBER        NOT NULL,
    UPLOAD_SEQ   NUMBER        NOT NULL,
    FILE_NM      VARCHAR2(255),
    FILE_TYPE    VARCHAR2(20),
    UPLOAD_DT    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    ROW_COUNT    NUMBER        DEFAULT 0,
    COL_COUNT    NUMBER        DEFAULT 0,
    CONSTRAINT PK_CHIPSET_UPLOAD_H PRIMARY KEY (UPLOAD_H_SEQ)
);

-- ── 히스토리: 칩 컬럼 ────────────────────────────────────────
CREATE TABLE IF NOT EXISTS CHIPSET_CHIP_COL_H (
    COL_H_SEQ   NUMBER        NOT NULL,
    COL_SEQ     NUMBER        NOT NULL,
    UPLOAD_SEQ  NUMBER        NOT NULL,
    VENDOR      VARCHAR2(100),
    COL_IDX     NUMBER,
    CHIP_NM     VARCHAR2(200),
    CHIP_DT     VARCHAR2(50),
    SORT_ORDER  NUMBER,
    CONSTRAINT PK_CHIPSET_CHIP_COL_H PRIMARY KEY (COL_H_SEQ)
);

-- ── 히스토리: 스펙 행 ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS CHIPSET_ROW_H (
    ROW_H_SEQ   NUMBER        NOT NULL,
    ROW_SEQ     NUMBER        NOT NULL,
    UPLOAD_SEQ  NUMBER        NOT NULL,
    DIMM        VARCHAR2(100),
    PRODUCT     VARCHAR2(200),
    VER         VARCHAR2(50),
    DENSITY     VARCHAR2(50),
    ORG         VARCHAR2(50),
    SPEED       VARCHAR2(100),
    SORT_ORDER  NUMBER,
    CONSTRAINT PK_CHIPSET_ROW_H PRIMARY KEY (ROW_H_SEQ)
);

-- ── 히스토리: 셀 값 ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS CHIPSET_CELL_H (
    CELL_H_SEQ  NUMBER        NOT NULL,
    CELL_SEQ    NUMBER        NOT NULL,
    ROW_SEQ     NUMBER        NOT NULL,
    COL_SEQ     NUMBER        NOT NULL,
    UPLOAD_SEQ  NUMBER        NOT NULL,
    CELL_VALUE  VARCHAR2(200),
    BG_COLOR    VARCHAR2(10),
    CONSTRAINT PK_CHIPSET_CELL_H PRIMARY KEY (CELL_H_SEQ)
);

-- ── 히스토리: Raw_Data 행 ─────────────────────────────────────
CREATE TABLE IF NOT EXISTS RAWDATA_ROW_H (
    RAWDATA_ROW_H_SEQ NUMBER        NOT NULL,
    RAWDATA_ROW_SEQ   NUMBER        NOT NULL,
    UPLOAD_SEQ        NUMBER        NOT NULL,
    COMPANY         VARCHAR2(100),
    SEG             VARCHAR2(100),
    CHIPSET         VARCHAR2(200),
    SOC_CS          VARCHAR2(200),
    PART_NUMBER     VARCHAR2(200),
    DRAM_PROCESS    VARCHAR2(100),
    FLASH_PROCESS   VARCHAR2(100),
    DENSITY         VARCHAR2(50),
    MLC_TLC         VARCHAR2(50),
    PKG             VARCHAR2(200),
    VAL1_DATE       VARCHAR2(20),
    VAL1_ENG        VARCHAR2(50),
    VAL1_STATUS     VARCHAR2(50),
    VAL1_REMARK     VARCHAR2(500),
    VAL2_DATE       VARCHAR2(20),
    VAL2_ENG        VARCHAR2(50),
    VAL2_STATUS     VARCHAR2(50),
    VAL2_REMARK     VARCHAR2(500),
    VAL3_DATE       VARCHAR2(20),
    VAL3_ENG        VARCHAR2(50),
    SORT_ORDER      NUMBER,
    CONSTRAINT PK_RAWDATA_ROW_H PRIMARY KEY (RAWDATA_ROW_H_SEQ)
);
